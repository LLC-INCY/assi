import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {resolve} from 'node:path';
const root=resolve(import.meta.dirname,'../apps/client/src-tauri');
const read=p=>readFileSync(resolve(root,p),'utf8');
const strings=s=>[...s.matchAll(/"([a-z0-9_-]+)"/g)].map(m=>m[1]);
const list=name=>strings(read('src/ipc_catalog.rs').split(`const ${name}:`)[1].split('];')[0]);
const handler=()=>read('src/lib.rs').split('tauri::generate_handler![')[1].split(']')[0].split(',').map(x=>x.trim().split('::').at(-1)).filter(Boolean);
const sorted=x=>[...x].sort();
const cap=n=>JSON.parse(read(`capabilities/${n}.json`));
function commandFor(permission){
 assert.match(permission,/^allow-[a-z0-9-]+$/);
 const filename=permission.slice(6).replaceAll('-','_');
 const source=read(`permissions/autogenerated/${filename}.toml`);
 const section=source.split('[[permission]]').find(s=>s.includes(`identifier = "${permission}"`));
 assert.ok(section,`missing generated permission ${permission}`);
 const commands=strings(section.split('commands.allow = [')[1]?.split(']')[0]||'');
 assert.equal(commands.length,1);return commands[0];
}
test('every registered IPC is inventoried and main is allowed exactly its commands',()=>{
 const all=list('ALL_COMMANDS');assert.equal(new Set(all).size,all.length);
 assert.deepEqual(sorted(all),sorted(handler()));
 assert.match(read('build.rs'),/commands\(ipc_catalog::ALL_COMMANDS\)/);
 assert.deepEqual(sorted(cap('main').permissions.map(commandFor)),sorted(all.filter(c=>c!=='session_overlay_snapshot')));
});
test('viewer permissions match registry and cannot grant host/access administration',()=>{
 const viewer=list('VIEWER_COMMANDS');assert.deepEqual(sorted(cap('viewer').permissions.map(commandFor)),sorted(viewer));
 for(const command of viewer){assert.ok(list('ALL_COMMANDS').includes(command));assert.ok(!/^(access_|session_host|session_accept$|session_reject$|session_capture_|session_overlay_)/.test(command),command);}
 for(const command of ['save_settings','session_audio_enable','session_clipboard_enable','session_terminal_allow','session_system_decide'])assert.ok(!viewer.includes(command));
 assert.deepEqual(cap('viewer').windows,['viewer-*']);
});
test('annotation overlay remains exact read-only and no remote origin is granted',()=>{
 assert.deepEqual(cap('overlay').permissions.map(commandFor),['session_overlay_snapshot']);
 assert.deepEqual(cap('overlay').windows,['annotations-overlay']);
 for(const name of readdirSync(resolve(root,'capabilities')).filter(n=>n.endsWith('.json'))){
  const c=JSON.parse(read(`capabilities/${name}`));assert.equal(c.remote,undefined);assert.notEqual(c.local,false);assert.equal(c.webviews,undefined);
  for(const label of c.windows){assert.ok(['main','annotations-overlay','viewer-*'].includes(label),label);if(label==='annotations-overlay')assert.equal(name,'overlay.json');}
 }
});
test('literal frontend invokes are registered, and main capability belongs only to main',()=>{
 const all=new Set(list('ALL_COMMANDS'));assert.deepEqual(cap('main').windows,['main']);
 const ui=resolve(root,'../ui');
 for(const name of readdirSync(ui).filter(n=>n.endsWith('.js'))){
  const source=readFileSync(resolve(ui,name),'utf8');
  for(const match of source.matchAll(/\binvoke\(\s*['"]([a-z0-9_]+)['"]/g))assert.ok(all.has(match[1]),`${name}: ${match[1]} not registered`);
 }
});
